#!/usr/bin/env python3
"""Generates the themed home-screen widget layouts and holder shapes.

RemoteViews cannot change fonts or shapes at runtime, so each style family
(soft, pop, pixel, sketch) gets its own layout with the same view ids. Holder
shapes are white drawables tinted at runtime (ImageView.setColorFilter), so any
theme color, including Custom, needs no extra resources.

Run from the repository root:  python3 tools/gen_widget_layouts.py
Use --check to verify the committed files are current.
"""
from __future__ import annotations

import sys
from pathlib import Path

RES = Path('android/app/src/main/res')
HEADER = '<?xml version="1.0" encoding="utf-8"?>\n<!-- Generated by tools/gen_widget_layouts.py; edit the generator, not this file. -->\n'

# style -> (outer radius dp, outline width dp, hard shadow dp, title font, title size sp)
STYLES = {
    'soft': (16, 1, 0, 'sans-serif-medium', 15),
    'pop': (14, 2, 3, 'sans-serif-black', 15),
    'pixel': (0, 2, 3, '@font/silkscreen', 13),
    'sketch': (18, 2, 0, '@font/caveat_variable', 19),
}
HOLDERS = 4
# Styles whose title font is bundled (not a system font).
BITMAP_TITLES = {'pixel', 'sketch'}
# Borders, shadow insets and taller display fonts use part of the same
# vertical budget. At normal text size every style needs 76dp per detailed
# holder, so choosing a design does not lose a card on the same grid.
VERTICAL_PADDING = {'soft': (8, 8), 'pop': (4, 4), 'pixel': (5, 6), 'sketch': (4, 5)}


def rounded(radius: float) -> str:
    return (HEADER + '<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">\n'
            '    <solid android:color="#FFFFFFFF" />\n'
            f'    <corners android:radius="{radius:g}dp" />\n'
            '</shape>\n')


def ring(radius: float, width: float) -> str:
    """Outline only, so a translucent fill never sits on top of it."""
    return (HEADER + '<shape xmlns:android="http://schemas.android.com/apk/res/android" android:shape="rectangle">\n'
            f'    <stroke android:width="{width:g}dp" android:color="#FFFFFFFF" />\n'
            f'    <corners android:radius="{radius:g}dp" />\n'
            '</shape>\n')


def _item(attrs: str) -> str:
    return (f'    <item {attrs}>\n'
            '        <shape android:shape="rectangle"><solid android:color="#FFFFFFFF" /></shape>\n'
            '    </item>\n')


def notched(step: int) -> str:
    """Square with stepped corners from non-overlapping strips (overlaps would
    darken where they meet once the holder is translucent)."""
    return (HEADER + '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">\n'
            + _item(f'android:left="{step}dp" android:right="{step}dp"')
            + _item(f'android:gravity="left|fill_vertical" android:width="{step}dp" android:top="{step}dp" android:bottom="{step}dp"')
            + _item(f'android:gravity="right|fill_vertical" android:width="{step}dp" android:top="{step}dp" android:bottom="{step}dp"')
            + '</layer-list>\n')


def notched_ring(step: int, width: int) -> str:
    """Outline of a notched square: four bars plus two step pieces per corner."""
    s, w = step, width
    items = [
        f'android:gravity="top|fill_horizontal" android:left="{s}dp" android:right="{s}dp" android:height="{w}dp"',
        f'android:gravity="bottom|fill_horizontal" android:left="{s}dp" android:right="{s}dp" android:height="{w}dp"',
        f'android:gravity="left|fill_vertical" android:top="{s}dp" android:bottom="{s}dp" android:width="{w}dp"',
        f'android:gravity="right|fill_vertical" android:top="{s}dp" android:bottom="{s}dp" android:width="{w}dp"',
    ]
    for v in ('top', 'bottom'):
        for h in ('left', 'right'):
            items.append(f'android:gravity="{v}|{h}" android:{h}="{s}dp" android:{v}="{w}dp" android:width="{w}dp" android:height="{s}dp"')
            items.append(f'android:gravity="{v}|{h}" android:{h}="{w}dp" android:{v}="{s}dp" android:width="{s - w}dp" android:height="{w}dp"')
    return (HEADER + '<layer-list xmlns:android="http://schemas.android.com/apk/res/android">\n'
            + ''.join(_item(a) for a in items) + '</layer-list>\n')


def drawables() -> dict[Path, str]:
    out: dict[Path, str] = {}
    d = RES / 'drawable'
    for style, (radius, outline, _, _, _) in STYLES.items():
        if style == 'pixel':
            out[d / 'widget_shape_pixel_shadow.xml'] = notched(3)
            out[d / 'widget_shape_pixel_ring.xml'] = notched_ring(3, outline)
            out[d / 'widget_shape_pixel_fill.xml'] = notched(3)
        else:
            out[d / f'widget_shape_{style}_shadow.xml'] = rounded(radius)
            out[d / f'widget_shape_{style}_ring.xml'] = ring(radius, outline)
            out[d / f'widget_shape_{style}_fill.xml'] = rounded(max(radius - outline, 0))
    return out


def text(view_id: str, size: int, *, font: str = 'sans-serif-medium', gone: bool = False, indent: str) -> str:
    vis = f'\n{indent}    android:visibility="gone"' if gone else ''
    return (f'{indent}<TextView\n'
            f'{indent}    android:id="@+id/{view_id}"\n'
            f'{indent}    android:layout_width="match_parent"\n'
            f'{indent}    android:layout_height="wrap_content"\n'
            f'{indent}    android:ellipsize="end"\n'
            f'{indent}    android:fontFamily="{font}"\n'
            f'{indent}    android:maxLines="1"\n'
            f'{indent}    android:textSize="{size}sp"{vis} />\n')


def holder(i: int, style: str) -> str:
    radius, outline, shadow, font, title_size = STYLES[style]
    top, bottom = VERTICAL_PADDING[style]
    shadow_shape = f'@drawable/widget_shape_{style}_shadow'
    ring_shape = f'@drawable/widget_shape_{style}_ring'
    fill_shape = f'@drawable/widget_shape_{style}_fill'
    ind = '        '
    parts = [
        f'    <FrameLayout\n'
        f'        android:id="@+id/holder_{i}"\n'
        f'        android:layout_width="match_parent"\n'
        f'        android:layout_height="wrap_content"\n'
        f'        android:layout_marginBottom="6dp"\n'
        f'        android:visibility="gone">\n',
    ]
    # Hard shadow (pop, pixel; solid surface only, since a translucent fill
    # would show it through): the outer shape offset down-right.
    parts.append(
        f'{ind}<ImageView\n'
        f'{ind}    android:id="@+id/holder_{i}_shadow"\n'
        f'{ind}    android:layout_width="match_parent"\n'
        f'{ind}    android:layout_height="match_parent"\n'
        f'{ind}    android:layout_marginStart="{shadow}dp"\n'
        f'{ind}    android:layout_marginTop="{shadow}dp"\n'
        f'{ind}    android:importantForAccessibility="no"\n'
        f'{ind}    android:scaleType="fitXY"\n'
        f'{ind}    android:src="{shadow_shape}"\n'
        f'{ind}    android:visibility="gone" />\n')
    parts.append(
        f'{ind}<ImageView\n'
        f'{ind}    android:id="@+id/holder_{i}_outline"\n'
        f'{ind}    android:layout_width="match_parent"\n'
        f'{ind}    android:layout_height="match_parent"\n'
        f'{ind}    android:layout_marginEnd="{shadow}dp"\n'
        f'{ind}    android:layout_marginBottom="{shadow}dp"\n'
        f'{ind}    android:importantForAccessibility="no"\n'
        f'{ind}    android:scaleType="fitXY"\n'
        f'{ind}    android:src="{ring_shape}" />\n')
    parts.append(
        f'{ind}<ImageView\n'
        f'{ind}    android:id="@+id/holder_{i}_fill"\n'
        f'{ind}    android:layout_width="match_parent"\n'
        f'{ind}    android:layout_height="match_parent"\n'
        f'{ind}    android:layout_marginStart="{outline}dp"\n'
        f'{ind}    android:layout_marginTop="{outline}dp"\n'
        f'{ind}    android:layout_marginEnd="{shadow + outline}dp"\n'
        f'{ind}    android:layout_marginBottom="{shadow + outline}dp"\n'
        f'{ind}    android:importantForAccessibility="no"\n'
        f'{ind}    android:scaleType="fitXY"\n'
        f'{ind}    android:src="{fill_shape}" />\n')
    parts.append(
        f'{ind}<LinearLayout\n'
        f'{ind}    android:layout_width="match_parent"\n'
        f'{ind}    android:layout_height="wrap_content"\n'
        f'{ind}    android:orientation="vertical"\n'
        f'{ind}    android:paddingStart="12dp"\n'
        f'{ind}    android:paddingTop="{top}dp"\n'
        f'{ind}    android:paddingEnd="{12 + shadow}dp"\n'
        f'{ind}    android:paddingBottom="{bottom + shadow}dp">\n')
    parts.append(text(f'holder_{i}_time', 12, indent=ind + '    '))
    parts.append(text(f'holder_{i}_title', title_size, font=font, indent=ind + '    '))
    if style in BITMAP_TITLES:
        # Launchers ignore app font resources in RemoteViews, so the renderer
        # draws these titles as white bitmaps and tints them (falls back to
        # the TextView above when the widget width is unknown).
        parts.append(
            f'{ind}    <ImageView\n'
            f'{ind}        android:id="@+id/holder_{i}_title_image"\n'
            f'{ind}        android:layout_width="wrap_content"\n'
            f'{ind}        android:layout_height="wrap_content"\n'
            f'{ind}        android:importantForAccessibility="no"\n'
            f'{ind}        android:scaleType="fitStart"\n'
            f'{ind}        android:visibility="gone" />\n')
    parts.append(text(f'holder_{i}_details', 12, font='sans-serif', gone=True, indent=ind + '    '))
    parts.append(f'{ind}</LinearLayout>\n')
    parts.append('    </FrameLayout>\n')
    return ''.join(parts)


def layout(style: str) -> str:
    caption = lambda n: (  # noqa: E731
        '    <TextView\n'
        f'        android:id="@+id/all_day_{n}"\n'
        '        android:layout_width="match_parent"\n'
        '        android:layout_height="wrap_content"\n'
        '        android:layout_marginBottom="4dp"\n'
        '        android:ellipsize="end"\n'
        '        android:maxLines="1"\n'
        '        android:paddingStart="4dp"\n'
        '        android:paddingEnd="4dp"\n'
        '        android:textColor="@color/widget_light_secondary"\n'
        '        android:textSize="12sp"\n'
        '        android:visibility="gone" />\n')
    return (HEADER +
            f'<!-- Themed widget, {style} style. Clear root: the wallpaper stays visible around the holders. -->\n'
            '<LinearLayout xmlns:android="http://schemas.android.com/apk/res/android"\n'
            '    android:id="@+id/widget_root"\n'
            '    android:layout_width="match_parent"\n'
            '    android:layout_height="match_parent"\n'
            '    android:background="@android:color/transparent"\n'
            '    android:orientation="vertical"\n'
            '    android:padding="8dp">\n\n'
            '    <TextView\n'
            '        android:id="@+id/widget_message"\n'
            '        android:layout_width="match_parent"\n'
            '        android:layout_height="wrap_content"\n'
            '        android:paddingStart="4dp"\n'
            '        android:paddingTop="4dp"\n'
            '        android:paddingEnd="4dp"\n'
            '        android:text="@string/widget_open_app"\n'
            '        android:textColor="@color/widget_light_primary"\n'
            '        android:textSize="15sp" />\n\n'
            + caption(0) + '\n' + caption(1) + '\n'
            + '\n'.join(holder(i, style) for i in range(HOLDERS))
            + '\n</LinearLayout>\n')


def font_family() -> str:
    return (HEADER + '<font-family xmlns:android="http://schemas.android.com/apk/res/android">\n'
            '    <font android:font="@font/silkscreen_regular" android:fontStyle="normal" android:fontWeight="400" />\n'
            '    <font android:font="@font/silkscreen_bold" android:fontStyle="normal" android:fontWeight="700" />\n'
            '</font-family>\n')


def files() -> dict[Path, str]:
    out = drawables()
    for style in STYLES:
        out[RES / 'layout' / f'widget_schedule_{style}.xml'] = layout(style)
    out[RES / 'font' / 'silkscreen.xml'] = font_family()
    return out


def main() -> int:
    check = '--check' in sys.argv
    stale = []
    for path, content in files().items():
        if check:
            if not path.exists() or path.read_text(encoding='utf-8') != content:
                stale.append(str(path))
        else:
            path.parent.mkdir(parents=True, exist_ok=True)
            path.write_bytes(content.encode('utf-8'))
    if stale:
        print('stale:', *stale, sep='\n  ')
        return 1
    print({'status': 'ok', 'files': len(files()), 'mode': 'check' if check else 'write'})
    return 0


if __name__ == '__main__':
    sys.exit(main())
