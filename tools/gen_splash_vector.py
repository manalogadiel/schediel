"""Generate the vector Schediel mark used by the launch splash.

Run: python tools/gen_splash_vector.py   (no dependencies)

Writes assets/branding/logo.svg (58x58 source) and
android/app/src/main/res/drawable/splash_vector.xml (108 viewport, logo
centered so Android 12's 288 dp splash icon shows it at ~154 dp, the size the
Flutter intro paints). lib/app/widgets/brand_mark.dart paints the same
numbers; keep them in sync. Raster launcher icons still come from
gen_brand_assets.py.
"""
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]

BODY = "#F4EADB"
LIP = "#E3D3B8"
EDGE = "#D6C3A1"
INK = "#233548"
CELL = "#CFC2AC"
TEAL = "#4F9D97"


def rrect(x, y, w, h, r):
    return (f"M{x + r},{y} H{x + w - r} A{r},{r} 0 0 1 {x + w},{y + r} V{y + h - r} "
            f"A{r},{r} 0 0 1 {x + w - r},{y + h} H{x + r} A{r},{r} 0 0 1 {x},{y + h - r} "
            f"V{y + r} A{r},{r} 0 0 1 {x + r},{y} Z")


HAIR = ("M6,25 L6,17 C6,10 12,6 19,6 L36,6 C42,6 46,4 50,1 C50,5 49,8 47,9 "
        "C50,10 52,13 52,17 L52,25 C46,21 38,19 29,19 C20,19 12,21 6,25 Z")
BRIDGE = "M26,26.5 L32,26.5"
CELLS = [(12, 38), (24, 38), (36, 38), (12, 46.5), (24, 46.5)]
TEAL_CELL = (36, 46.5)

shapes = [
    ("fill", LIP, rrect(6, 17.5, 46, 39, 9)),
    ("fill", BODY, rrect(6, 15, 46, 39, 9)),
    ("stroke", EDGE, rrect(6.4, 15.4, 45.2, 38.2, 8.6), 0.8),
    ("fill", INK, HAIR),
    ("lens", rrect(10, 21.5, 16, 11, 3.5)),
    ("lens", rrect(32, 21.5, 16, 11, 3.5)),
    ("stroke", INK, BRIDGE, 3),
] + [("fill", CELL, rrect(x, y, 10, 6, 1.8)) for x, y in CELLS] + [("fill", TEAL, rrect(*TEAL_CELL, 10, 6, 1.8))]

svg = ['<!-- Schediel mark (original). Generated by tools/gen_splash_vector.py; edit geometry there. -->',
       '<svg xmlns="http://www.w3.org/2000/svg" width="58" height="58" viewBox="0 0 58 58">']
xml = ['<?xml version="1.0" encoding="utf-8"?>',
       '<!-- Schediel mark for the system splash; generated by tools/gen_splash_vector.py. -->',
       '<vector xmlns:android="http://schemas.android.com/apk/res/android"',
       '    android:width="108dp" android:height="108dp"',
       '    android:viewportWidth="108" android:viewportHeight="108">',
       '    <group android:translateX="25" android:translateY="25">']
for s in shapes:
    if s[0] == "fill":
        svg.append(f'  <path d="{s[2]}" fill="{s[1]}"/>')
        xml.append(f'        <path android:fillColor="{s[1]}" android:pathData="{s[2]}"/>')
    elif s[0] == "stroke":
        svg.append(f'  <path d="{s[2]}" fill="none" stroke="{s[1]}" stroke-width="{s[3]}" stroke-linecap="round" stroke-linejoin="round"/>')
        xml.append(f'        <path android:strokeColor="{s[1]}" android:strokeWidth="{s[3]}" android:strokeLineCap="round" '
                   f'android:strokeLineJoin="round" android:pathData="{s[2]}"/>')
    else:  # lens: faint fill + ink frame
        svg.append(f'  <path d="{s[1]}" fill="#FFFFFF" fill-opacity="0.45" stroke="{INK}" stroke-width="3" stroke-linejoin="round"/>')
        xml.append(f'        <path android:fillColor="#73FFFFFF" android:strokeColor="{INK}" android:strokeWidth="3" '
                   f'android:strokeLineJoin="round" android:pathData="{s[1]}"/>')
svg.append('</svg>')
xml += ['    </group>', '</vector>']

(ROOT / "assets/branding/logo.svg").write_text("\n".join(svg) + "\n", encoding="utf-8", newline="\n")
(ROOT / "android/app/src/main/res/drawable/splash_vector.xml").write_text("\n".join(xml) + "\n", encoding="utf-8", newline="\n")
print("ok")
