const _path = 'contracts/fixtures/widget-snapshot-v1_1-cases.json';

/// Builds the shared 1.1 fixture from the Dart builder. The Kotlin reader
/// test reads the same file, so both sides agree on shape and colors.
/// Regenerate with: UPDATE_FIXTURES=1 flutter test test/contracts/widget_snapshot_v1_1_fixture_test.dart
Map<String, Object?> buildFixture() {
  final zones = ZoneResolver.initialized();
  final builder = WidgetSnapshotBuilder(zones, OccurrenceEngine(zones));
  ScheduleSeries s(String id, String title, int hour, String? category) => ScheduleSeries(
        id: id,
        revision: 1,
        title: title,
        categoryId: category,
        time: TimedSpec(
          startDate: LocalDate(2026, 11, 2),
          startTime: LocalTime(hour, 0),
          timeZone: 'Asia/Manila',
          endTime: LocalTime(hour + 1, 0),
          endDayOffset: 0,
        ),
        recurrence: RecurrenceSpec(frequency: RecurrenceFrequency.weekly, weekdays: const [1]),
        details: const ScheduleDetails(location: 'Fixture room'),
      );
  final theme = widgetThemeJson(themeFor(ThemeId.pixel), ThemeMode.system);
  final snapshot = builder.build(
    series: [
      s('00000000-0000-4000-8000-000000000011', 'Fixture themed A', 9, 'school'),
      s('00000000-0000-4000-8000-000000000012', 'Fixture themed B', 11, null),
    ],
    configs: [
      WidgetConfig.defaults,
      WidgetConfig.defaults.copyWith(widgetKey: '21', useAppTheme: false, surface: WidgetSurface.solid),
    ],
    now: DateTime.utc(2026, 11, 2, 0, 0),
    zone: 'Asia/Manila',
    dataRevision: 3,
    use24h: true,
    theme: theme,
    categoryColors: const {'school': 'green'},
  );
  final light = theme['light']! as Map<String, Object?>;
  final dark = theme['dark']! as Map<String, Object?>;
  String hex(HolderColors c) => '#${(c.fill.toARGB32()).toRadixString(16).padLeft(8, '0').toUpperCase()}';
  String rgb(Color c) => '#${(c.toARGB32() & 0xFFFFFF).toRadixString(16).padLeft(6, '0').toUpperCase()}';
  final nextLight = holderColors(light, next: true, surface: 'clear');
  final schoolLight = holderColors(light, next: false, categoryColor: 'green', surface: 'clear');
  final neutralDarkSolid = holderColors(dark, next: false, surface: 'solid');
  return {
    'description': 'Contract 1.1 (themed) snapshot generated by the Dart builder from fixed inputs; '
        'Android reads it in SnapshotReaderThemeTest. Expected holder colors are ARGB with the surface opacity applied.',
    'deviceTimeZone': 'Asia/Manila',
    'now': '2026-11-02T00:00:00Z',
    'snapshot': snapshot,
    'expect': {
      'style': 'pixel',
      'defaultUseAppTheme': true,
      'widget21UseAppTheme': false,
      'next': '00000000-0000-4000-8000-000000000011/2026-11-02',
      'nextCategoryColor': 'green',
      'upcomingCategoryColor': null,
      'holders': {
        'lightNextClear': {'fill': hex(nextLight), 'ink': rgb(nextLight.ink)},
        'lightGreenClear': {'fill': hex(schoolLight), 'ink': rgb(schoolLight.ink)},
        'darkNeutralSolid': {'fill': hex(neutralDarkSolid), 'ink': rgb(neutralDarkSolid.ink)},
      },
    },
  };
}

void main() {
  test('the committed 1.1 fixture matches the Dart builder', () {
    final fixture = buildFixture();
    final encoded = '${const JsonEncoder.withIndent('  ').convert(fixture)}\n';
    final file = File(_path);
    if (Platform.environment['UPDATE_FIXTURES'] == '1' || !file.existsSync()) {
      file.writeAsStringSync(encoded);
    }
    expect(jsonDecode(file.readAsStringSync()), jsonDecode(encoded));
  });
}
